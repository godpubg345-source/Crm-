from django.db import transaction
from rest_framework.exceptions import ValidationError
import datetime
from .models import Student, Lead

class StudentService:
    """
    Service layer for Student business logic.
    Decouples complex operations like Lead Conversion from ViewSets.
    """

    @staticmethod
    @transaction.atomic
    def convert_lead(lead: Lead, user):
        """
        Convert a Lead into a Student.
        Student code is auto-generated by pre_save signal.
        """
        if lead.status == Lead.Status.CONVERTED:
            raise ValidationError("Lead is already converted.")
            
        try:
            # Create Student
            # Note: student_code is NOT passed here, signal will handle it.
            student = Student.objects.create(
                lead=lead,
                branch=lead.branch,
                first_name=lead.first_name,
                last_name=lead.last_name,
                email=lead.email,
                phone=lead.phone,
                counselor=lead.assigned_to, # Inherit counselor from Lead
                source=lead.source,
                status=Student.Status.ACTIVE
            )
            
            # Update Lead status
            lead.status = Lead.Status.CONVERTED
            lead.save()
            
            return student

        except Exception as e:
            # Re-raise as ValidationError for standard API error handling
            raise ValidationError(f"Failed to convert lead: {str(e)}")

class LeadService:
    """
    Service layer for Lead business logic.
    Handles complex operations like Intelligent Auto-Assignment (Geo-routing & Round Robin).
    """

    @staticmethod
    def assign_lead_to_counselor(lead: Lead):
        """
        Intelligent assignment logic:
        1. Base Pool: All Counselors in the Lead's Branch (if any).
        2. Geo-Routing: Filter Counselors specializing in the Lead's target_country.
           If no specialists exist, fallback to all counselors in the branch.
        3. Round-Robin / Load Balancing: Assign to the counselor with the fewest active leads.
        """
        if lead.assigned_to:
            return lead # Already assigned

        from apps.identity.accounts.models import User
        from django.db.models import Count, Q

        # Base pool: Active Counselors
        counselors = User.objects.filter(role=User.Role.COUNSELOR, is_active=True)
        
        # 1. Branch Isolation
        if lead.branch:
            counselors = counselors.filter(branch=lead.branch)
            
        if not counselors.exists():
            return lead # No eligible counselors to assign to

        # 2. Geo-Routing (Specialty matching)
        target = lead.target_country
        specialists = counselors
        if target:
            # Look for counselors whose dossier.specialties JSON array contains the target country
            # This uses Django's JSONField contains lookup
            geo_matched_counselors = counselors.filter(dossier__specialties__contains=target)
            if geo_matched_counselors.exists():
                specialists = geo_matched_counselors
        
        # 3. Load Balancing (Round-Robin by fewest active leads)
        # Annotate each counselor with their count of currently active leads
        specialists = specialists.annotate(
            active_lead_count=Count('assigned_leads', filter=Q(assigned_leads__is_active=True))
        ).order_by('active_lead_count', '?') # '?' resolves ties randomly

        selected_counselor = specialists.first()

        if selected_counselor:
            lead.assigned_to = selected_counselor
            lead.save(update_fields=['assigned_to'])
            
        return lead
